//! `zig build gen-wayland`: combines `wayland-scanner private-code` outputs
//! into one static C file (`src/platform/wayland/proto_tables.c`) exposing a
//! single `rex_wayland_interfaces()` accessor, avoiding symbol collisions with
//! `libglfw.a` and keeping zero link-time dependency on `libwayland-client`.

const std = @import("std");
const ucd = @import("ucd.zig");

const gen_name = "wayland";
const usage_args = "<out.c> <protocol-code.c>...";

const exported_interfaces = [_]struct { field: []const u8, symbol: []const u8 }{
    .{ .field = "xdg_wm_base", .symbol = "xdg_wm_base_interface" },
    .{ .field = "xdg_surface", .symbol = "xdg_surface_interface" },
    .{ .field = "xdg_toplevel", .symbol = "xdg_toplevel_interface" },
    .{ .field = "xdg_decoration_manager", .symbol = "zxdg_decoration_manager_v1_interface" },
    .{ .field = "xdg_toplevel_decoration", .symbol = "zxdg_toplevel_decoration_v1_interface" },
    .{ .field = "fractional_scale_manager", .symbol = "wp_fractional_scale_manager_v1_interface" },
    .{ .field = "fractional_scale", .symbol = "wp_fractional_scale_v1_interface" },
    .{ .field = "viewporter", .symbol = "wp_viewporter_interface" },
    .{ .field = "viewport", .symbol = "wp_viewport_interface" },
    .{ .field = "text_input_manager", .symbol = "zwp_text_input_manager_v3_interface" },
    .{ .field = "text_input", .symbol = "zwp_text_input_v3_interface" },
    .{ .field = "primary_selection_manager", .symbol = "zwp_primary_selection_device_manager_v1_interface" },
    .{ .field = "primary_selection_device", .symbol = "zwp_primary_selection_device_v1_interface" },
    .{ .field = "primary_selection_source", .symbol = "zwp_primary_selection_source_v1_interface" },
    .{ .field = "primary_selection_offer", .symbol = "zwp_primary_selection_offer_v1_interface" },
    .{ .field = "xdg_activation", .symbol = "xdg_activation_v1_interface" },
    .{ .field = "xdg_activation_token", .symbol = "xdg_activation_token_v1_interface" },
    .{ .field = "xdg_system_bell", .symbol = "xdg_system_bell_v1_interface" },
    .{ .field = "cursor_shape_manager", .symbol = "wp_cursor_shape_manager_v1_interface" },
    .{ .field = "cursor_shape_device", .symbol = "wp_cursor_shape_device_v1_interface" },
};

pub fn main(init: std.process.Init) !void {
    var args = init.minimal.args.iterate();
    _ = args.skip(); // argv[0]
    const out_path = args.next() orelse ucd.usage(gen_name, usage_args);

    const io = init.io;
    const allocator = init.arena.allocator();

    var stdout_buf: [8192]u8 = undefined;
    var writer = (try ucd.createFile(io, out_path)).writer(io, &stdout_buf);
    defer writer.flush() catch {};
    const w = &writer.interface;

    try w.writeAll(
        \\/* Generated by `zig build gen-wayland`. Do not edit by hand.
        \\ * Combines `wayland-scanner private-code` tables into static storage with
        \\ * one exported accessor so Rex links no Wayland library and never collides
        \\ * with other protocol table copies in the same binary.
        \\ */
        \\#include <stdlib.h>
        \\#include <stdint.h>
        \\#include <wayland-util.h>
        \\
        \\#define WL_PRIVATE static
        \\
        \\
    );

    var seen_decls: std.StringHashMapUnmanaged(void) = .empty;
    var file_count: usize = 0;

    while (args.next()) |in_path| {
        const content = try ucd.readFile(io, allocator, gen_name, in_path);
        try emitSanitized(w, allocator, &seen_decls, content);
        file_count += 1;
    }

    try w.writeAll(
        \\
        \\typedef struct RexWaylandInterfaces {
        \\
    );
    for (exported_interfaces) |item| {
        try w.print("    const struct wl_interface *{s};\n", .{item.field});
    }
    try w.writeAll(
        \\} RexWaylandInterfaces;
        \\
        \\static const RexWaylandInterfaces rex_wl_interfaces_table = {
        \\
    );
    for (exported_interfaces) |item| {
        try w.print("    .{s} = &{s},\n", .{ item.field, item.symbol });
    }
    try w.writeAll(
        \\};
        \\
        \\const RexWaylandInterfaces *rex_wayland_interfaces(void) {
        \\    return &rex_wl_interfaces_table;
        \\}
        \\
    );

    ucd.log(gen_name, "wrote {s} from {d} protocol files", .{ std.fs.path.basename(out_path), file_count });
}

fn emitSanitized(
    w: *std.Io.Writer,
    allocator: std.mem.Allocator,
    seen_decls: *std.StringHashMapUnmanaged(void),
    content: []const u8,
) !void {
    var lines = std.mem.splitScalar(u8, content, '\n');
    var skip_depth: usize = 0;

    while (lines.next()) |raw_line| {
        const line = std.mem.trimEnd(u8, raw_line, "\r");
        const trimmed = std.mem.trimStart(u8, line, " \t");

        if (skip_depth > 0) {
            if (std.mem.startsWith(u8, trimmed, "#if")) {
                skip_depth += 1;
            } else if (std.mem.startsWith(u8, trimmed, "#endif")) {
                skip_depth -= 1;
            }
            continue;
        }
        if (std.mem.startsWith(u8, trimmed, "#ifndef WL_PRIVATE") or
            std.mem.startsWith(u8, trimmed, "#ifndef __has_attribute") or
            std.mem.startsWith(u8, trimmed, "#if (__has_attribute"))
        {
            skip_depth = 1;
            continue;
        }
        if (std.mem.startsWith(u8, trimmed, "#include ")) {
            continue;
        }

        const extern_prefix = "extern const struct wl_interface ";
        if (std.mem.startsWith(u8, line, extern_prefix)) {
            const rest = line[extern_prefix.len..];
            if (!seen_decls.contains(rest)) {
                const owned = try allocator.dupe(u8, rest);
                try seen_decls.put(allocator, owned, {});
                try w.print("static const struct wl_interface {s}\n", .{rest});
            }
            continue;
        }

        try w.print("{s}\n", .{line});
    }
}
