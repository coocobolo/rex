//! Translates GLFW key codes and modifier bits into Rex's `Key` and
//! `Modifiers`. The only place outside the window code that names GLFW's
//! key constants (ADR 0001, ADR 0007).

const c = @import("glfw");

const Key = @import("../input/key.zig").Key;
const Modifiers = @import("../input/key.zig").Modifiers;

/// The modifiers in a GLFW modifier bit field.
pub fn modifiers(mods: c_int) Modifiers {
    return .{
        .shift = (mods & c.GLFW_MOD_SHIFT) != 0,
        .ctrl = (mods & c.GLFW_MOD_CONTROL) != 0,
        .alt = (mods & c.GLFW_MOD_ALT) != 0,
        .super = (mods & c.GLFW_MOD_SUPER) != 0,
    };
}

