//! Helpers shared by the table generators in tools/gen/.
//!
//! Every generator has the same shape: `<generator> <out.zig> <input>...`
//! reads its inputs, writes one Zig source file starting with
//! `writeHeader`, and logs what it read and wrote to stderr. build.zig
//! runs it for `zig build gen-<name>` and copies the output into src/.

const std = @import("std");
const mem = std.mem;

/// One parsed UCD data line: `first..last ; value # comment`.
pub const Line = struct { first: u21, last: u21, value: []const u8 };

/// Parses a UCD data line. Returns null for blank and comment-only lines.
/// `value` is the first field after the code points, trimmed.
pub fn parseLine(raw: []const u8) !?Line {
    const hash = mem.indexOfScalar(u8, raw, '#') orelse raw.len;
    const line = mem.trim(u8, raw[0..hash], " \t\r");
    if (line.len == 0) return null;
    const semi = mem.indexOfScalar(u8, line, ';') orelse return null;
    const cps = mem.trim(u8, line[0..semi], " \t");
    const rest = line[semi + 1 ..];
    const end = mem.indexOfScalar(u8, rest, ';') orelse rest.len;
    const value = mem.trim(u8, rest[0..end], " \t");
    if (mem.indexOf(u8, cps, "..")) |dots| return .{
        .first = try std.fmt.parseInt(u21, cps[0..dots], 16),
        .last = try std.fmt.parseInt(u21, cps[dots + 2 ..], 16),
        .value = value,
    };
    const cp = try std.fmt.parseInt(u21, cps, 16);
    return .{ .first = cp, .last = cp, .value = value };
}

/// Reads a whole input file and logs it as `<name>: read <path>`.
pub fn readFile(io: std.Io, gpa: mem.Allocator, name: []const u8, path: []const u8) ![]u8 {
    const file = try std.Io.Dir.openFile(.cwd(), io, path, .{ .mode = .read_only });
    defer file.close(io);
    const len = try file.length(io);
    const buf = try gpa.alloc(u8, len);
    errdefer gpa.free(buf);
    if (try file.readPositionalAll(io, buf, 0) != len) return error.ShortRead;
    log(name, "read {s} ({d} bytes)", .{ path, len });
    return buf;
}

/// Creates (or truncates) the output file.
pub fn createFile(io: std.Io, path: []const u8) !std.Io.File {
    return std.Io.Dir.createFile(.cwd(), io, path, .{});
}

/// UCD version of an input under tools/ucd/<version>/.
pub fn versionOf(path: []const u8) []const u8 {
    const dir = std.fs.path.dirname(path) orelse return "unknown";
    return std.fs.path.basename(dir);
}

/// Writes the first line every generated file starts with:
/// `// GENERATED by zig build gen-<name> from <source>. DO NOT EDIT.`
pub fn writeHeader(w: *std.Io.Writer, name: []const u8, comptime source: []const u8, args: anytype) !void {
    try w.print("// GENERATED by zig build gen-{s} from " ++ source ++ ". DO NOT EDIT.\n", .{name} ++ args);
}

/// Logs one line to stderr, prefixed with the generator name.
pub fn log(name: []const u8, comptime fmt: []const u8, args: anytype) void {
    std.debug.print("gen-{s}: " ++ fmt ++ "\n", .{name} ++ args);
}

/// Prints `usage` to stderr and exits with status 2.
pub fn usage(name: []const u8, args: []const u8) noreturn {
    std.debug.print("usage: gen-{s} {s}\n", .{ name, args });
    std.process.exit(2);
}
