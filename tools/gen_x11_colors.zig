//! Generates src/color/x11_colors.zig from rgb.txt.
//!
//! Usage: gen_x11_colors <path/to/rgb.txt> > src/color/x11_colors.zig
//!
//! Find rgb.txt from:
//!
//! `$ find /usr -name rgb.txt 2>/dev/null` or
//! https://cgit.freedesktop.org/xorg/app/rgb/plain/rgb.txt

const std = @import("std");
const log = std.log.scoped(.gen_x11_colors);

pub fn main(init: std.process.Init) !void {
    var args = init.minimal.args.iterate();

    if (args.inner.remaining.len < 2) {
        log.info("Usage: gen_x11_colors <path/to/rgb.txt> > output.zig", .{});
        std.process.exit(0);
    }

    _ = args.skip(); // skip argv[0]

    const source_path = args.next() orelse {
        log.err("expected rgb.txt data source file, got null\n", .{});
        std.process.exit(1);
    };

    if (source_path.len == 0) {
        log.err("expected rgb.txt data source file, got null\n", .{});
        std.process.exit(1);
    }

    const io = init.io;
    const allocator = init.arena.allocator();

    const content = blk: {
        const file = try std.Io.Dir.openFile(.cwd(), io, source_path, .{});
        defer file.close(io);

        const file_len = try file.length(io);
        const buffer = try allocator.alloc(u8, file_len);
        const n = try file.readPositionalAll(io, buffer, 0);
        if (n != file_len) return error.FileSizeMismatched;
        break :blk buffer;
    };
    defer allocator.free(content);

    // log.debug("{s}", .{content});

    var stdout_buf: [4096]u8 = undefined;
    var writer = std.Io.File.stdout().writer(io, &stdout_buf);
    defer writer.flush() catch {};

    try parse(&writer.interface, allocator, content);
}

fn parse(writer: *std.Io.Writer, gpa: std.mem.Allocator, content: []const u8) !void {
    var seen: std.StringHashMap(void) = .init(gpa);
    defer {
        var it = seen.keyIterator();
        while (it.next()) |k| gpa.free(k.*);
        seen.deinit();
    }

    try writer.writeAll(
        \\//! Generated by tools/gen_x1_colors.zig — do not edit.
        \\//! Source: rgb.txt
        \\//! Regenerate: zig build gen-x11-colors
        \\//!
        \\//! Generator emit lowercase keys, keep both forms "ghost white" 
        \\//! and "ghostwhite" both appear as separate entries.
        \\
        \\const std = @import("std");
        \\const Rgb = @import("rgb.zig");
        \\
        \\pub const colors_map = std.StaticStringMap(Rgb).initComptime(&.{
        \\
    );

    var lines = std.mem.splitScalar(u8, content, '\n');
    while (lines.next()) |line| {
        const t = std.mem.trim(u8, line, " \t\r");
        if (t.len == 0 or t[0] == '!') continue;

        // rgb.txt format: "R  G  B\t\tColor Name"
        var tok = std.mem.tokenizeAny(u8, t, " \t");
        const r = std.fmt.parseInt(u8, tok.next() orelse continue, 10) catch continue;
        const g = std.fmt.parseInt(u8, tok.next() orelse continue, 10) catch continue;
        const b = std.fmt.parseInt(u8, tok.next() orelse continue, 10) catch continue;
        const name = std.mem.trim(u8, tok.rest(), " \t");
        if (name.len == 0) continue;

        const lower = try std.ascii.allocLowerString(gpa, name);
        const gop = try seen.getOrPut(lower);
        if (gop.found_existing) {
            gpa.free(lower);
            continue;
        }

        try writer.print(
            "    .{{ \"{s}\", Rgb{{ .r = {d}, .g = {d}, .b = {d} }} }},\n",
            .{ lower, r, g, b },
        );
    }

    try writer.writeAll("});\n");

    try writer.writeAll(
        \\
        \\/// Lookup: lowercase only, no space stripping  
        \\pub fn fromName(name: []const u8) ?Rgb {  
        \\    var buf: [64]u8 = undefined;  
        \\    if (name.len > buf.len) return null;  
        \\    const lower = std.ascii.lowerString(&buf, name);  
        \\    return colors_map.get(lower);  
        \\}
    );
}
