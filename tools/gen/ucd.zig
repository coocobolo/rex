//! Helpers shared by the table generators in tools/gen/.
//!
//! Every generator reads `<out.zig> <input>...`, writes one Zig source file
//! starting with `writeHeader`, and logs to stderr; UCD generators also take
//! an optional trailing `--malformed=reject|skip` (default `reject`). build.zig
//! runs each generator for `zig build gen-<name>` and copies the output into src/.

const std = @import("std");
const mem = std.mem;

/// Maximum fields on a UCD data line (UnicodeData.txt has 15).
pub const max_fields = 15;

/// One parsed UCD data line: `first..last ; field0 ; field1 ... # comment`.
/// `fields` borrows the caller's buffer; `value` is the first field.
pub const Line = struct {
    first: u21,
    last: u21,
    value: []const u8,
    fields: []const []const u8,
};

/// How a generator treats a malformed UCD value. `reject` fails the build;
/// `skip` drops the offending line and continues.
pub const Malformed = enum { reject, skip };

/// Parses `--malformed=<reject|skip>`; null means the argument is unknown.
pub fn parseMalformed(arg: []const u8) ?Malformed {
    if (mem.eql(u8, arg, "--malformed=reject")) return .reject;
    if (mem.eql(u8, arg, "--malformed=skip")) return .skip;
    return null;
}

/// Reads the optional trailing malformed argument, defaulting to `reject`.
pub fn malformedFromArgs(args: *std.process.Args.Iterator, name: []const u8, args_doc: []const u8) Malformed {
    const arg = args.next() orelse return .reject;
    const policy = parseMalformed(arg) orelse usage(name, args_doc);
    if (args.next() != null) usage(name, args_doc);
    return policy;
}

/// Converts a parsed code point to u21 under `policy`. Null means skip the
/// line; `reject` returns an error instead.
pub fn codePoint(raw: u64, policy: Malformed) !?u21 {
    if (std.math.cast(u21, raw)) |cp| return cp;
    if (policy == .skip) return null;
    return error.MalformedCodePoint;
}

/// Parses a UCD data line into `first..last ; field0 ; field1 ... # comment`.
/// `field_buf` holds the trimmed fields; the returned `Line.fields` borrows it.
/// Returns null for blank, comment-only and skipped malformed lines; a
/// reversed range is rejected or skipped according to `policy`.
pub fn parseLine(raw: []const u8, policy: Malformed, field_buf: *[max_fields][]const u8) !?Line {
    const hash = mem.indexOfScalar(u8, raw, '#') orelse raw.len;
    const line = mem.trim(u8, raw[0..hash], " \t\r");
    if (line.len == 0) return null;
    const semi = mem.indexOfScalar(u8, line, ';') orelse return null;
    const cps = mem.trim(u8, line[0..semi], " \t");

    var rest = line[semi + 1 ..];
    var count: usize = 0;
    while (count < field_buf.len) {
        const next = mem.indexOfScalar(u8, rest, ';');
        field_buf[count] = mem.trim(u8, if (next) |i| rest[0..i] else rest, " \t");
        count += 1;
        if (next) |i| {
            rest = rest[i + 1 ..];
        } else break;
    }

    var first: u21 = undefined;
    var last: u21 = undefined;
    if (mem.indexOf(u8, cps, "..")) |dots| {
        first = (try codePoint(try std.fmt.parseInt(u64, cps[0..dots], 16), policy)) orelse return null;
        last = (try codePoint(try std.fmt.parseInt(u64, cps[dots + 2 ..], 16), policy)) orelse return null;
    } else {
        first = (try codePoint(try std.fmt.parseInt(u64, cps, 16), policy)) orelse return null;
        last = first;
    }
    if (first > last) {
        if (policy == .reject) return error.MalformedRange;
        return null;
    }
    return .{ .first = first, .last = last, .value = field_buf[0], .fields = field_buf[0..count] };
}

/// Reads a whole input file and logs it as `<name>: read <path>`.
pub fn readFile(io: std.Io, gpa: mem.Allocator, name: []const u8, path: []const u8) ![]u8 {
    const file = try std.Io.Dir.openFile(.cwd(), io, path, .{ .mode = .read_only });
    defer file.close(io);
    const len = try file.length(io);
    const buf = try gpa.alloc(u8, len);
    errdefer gpa.free(buf);
    if (try file.readPositionalAll(io, buf, 0) != len) return error.ShortRead;
    log(name, "read {s} ({d} bytes)", .{ path, len });
    return buf;
}

/// Creates (or truncates) the output file.
pub fn createFile(io: std.Io, path: []const u8) !std.Io.File {
    return std.Io.Dir.createFile(.cwd(), io, path, .{});
}

/// UCD version of an input under tools/ucd/<version>/.
pub fn versionOf(path: []const u8) []const u8 {
    const dir = std.fs.path.dirname(path) orelse return "unknown";
    return std.fs.path.basename(dir);
}

/// Writes the first line every generated file starts with:
/// `// GENERATED by zig build gen-<name> from <source>. DO NOT EDIT.`
pub fn writeHeader(w: *std.Io.Writer, name: []const u8, comptime source: []const u8, args: anytype) !void {
    try w.print("// GENERATED by zig build gen-{s} from " ++ source ++ ". DO NOT EDIT.\n", .{name} ++ args);
}

/// Logs one line to stderr, prefixed with the generator name.
pub fn log(name: []const u8, comptime fmt: []const u8, args: anytype) void {
    std.debug.print("gen-{s}: " ++ fmt ++ "\n", .{name} ++ args);
}

/// Prints `usage` to stderr and exits with status 2.
pub fn usage(name: []const u8, args: []const u8) noreturn {
    std.debug.print("usage: gen-{s} {s}\n", .{ name, args });
    std.process.exit(2);
}
