    right_control,
    left_alt,
    right_alt,
    left_super,
    right_super,

    pub fn isModifier(self: Key) bool {
        return switch (self) {
            .left_shift,
            .right_shift,
            .left_control,
            .right_control,
            .left_alt,
            .right_alt,
            .left_super,
            .right_super,
            => true,
            else => false,
        };
    }
};
