//! Rex's own keys and modifiers, as key bindings, the UI and the key
//! encoder name them. No platform type appears here: the platform layer
//! translates its key codes into these (ADR 0001, ADR 0007).

/// The modifiers held with a key.
pub const Modifiers = packed struct(u8) {
    shift: bool = false,
    ctrl: bool = false,
    alt: bool = false,
    super: bool = false,
    _: u4 = 0,

    pub const none: Modifiers = .{};

    pub fn hasAny(self: Modifiers) bool {
        return self.shift or self.ctrl or self.alt or self.super;
    }
};

